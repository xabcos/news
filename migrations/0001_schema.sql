-- The schema of xabcnews.com and the public topics it starts with.

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    status boolean NOT NULL DEFAULT true,
    role text NOT NULL DEFAULT 'user',
    pro_until timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_login_at timestamptz,
    CONSTRAINT users_email_valid CHECK (email = lower(email) AND email = btrim(email) AND char_length(email) BETWEEN 3 AND 254),
    CONSTRAINT users_role_valid CHECK (role IN ('user', 'admin'))
);
CREATE INDEX users_active_last_login_idx ON users (last_login_at DESC) WHERE status AND last_login_at IS NOT NULL;

CREATE TABLE user_metrics (
    id boolean PRIMARY KEY DEFAULT true CHECK (id),
    registered_count bigint NOT NULL CHECK (registered_count >= 0)
);
INSERT INTO user_metrics (registered_count) VALUES (0);

CREATE FUNCTION maintain_user_metrics() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE user_metrics
    SET registered_count = CASE TG_OP
        WHEN 'INSERT' THEN registered_count + 1
        WHEN 'DELETE' THEN registered_count - 1
        WHEN 'TRUNCATE' THEN 0
    END
    WHERE id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'user_metrics singleton row is missing';
    END IF;
    RETURN NULL;
END;
$$;
CREATE TRIGGER users_metrics_count AFTER INSERT OR DELETE ON users FOR EACH ROW EXECUTE FUNCTION maintain_user_metrics();
CREATE TRIGGER users_metrics_truncate AFTER TRUNCATE ON users FOR EACH STATEMENT EXECUTE FUNCTION maintain_user_metrics();

