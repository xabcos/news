-- 𝑳𝑳𝑴 keeps mainstream model prices and specs from each provider's own documentation.
-- Providers come and go without an administrator: listed providers are read every day, and
-- a weekly pass adds providers the news reports with an official API, retries candidates and
-- retires providers whose pages stay unreadable. `enabled` is the workspace's pause switch.
CREATE TABLE llm_vendors (
    id text PRIMARY KEY CONSTRAINT llm_vendors_id_valid CHECK (id ~ '^[a-z0-9][a-z0-9-]{0,31}$'),
    name text NOT NULL CONSTRAINT llm_vendors_name_valid CHECK (char_length(name) BETWEEN 1 AND 60),
    name_en text NOT NULL CONSTRAINT llm_vendors_name_en_valid CHECK (char_length(name_en) BETWEEN 1 AND 60),
    region text NOT NULL CONSTRAINT llm_vendors_region_valid CHECK (region IN ('cn', 'global')),
    homepage text NOT NULL,
    -- Hosts (and their subdomains) that count as this provider's official documentation.
    domains text[] NOT NULL CONSTRAINT llm_vendors_domains_valid CHECK (cardinality(domains) BETWEEN 1 AND 8),
    -- Collection scope read by the extraction model, e.g. which families are first-party.
    note text NOT NULL DEFAULT '' CONSTRAINT llm_vendors_note_valid CHECK (char_length(note) <= 500),
    enabled boolean NOT NULL DEFAULT true,
    -- Listed and read daily, waiting for an official price list that can be read, or retired.
    state text NOT NULL DEFAULT 'active'
        CONSTRAINT llm_vendors_state_valid CHECK (state IN ('active', 'candidate', 'offline')),
    -- Registered here, or found in the news by the weekly pass.
    origin text NOT NULL DEFAULT 'seed'
        CONSTRAINT llm_vendors_origin_valid CHECK (origin IN ('seed', 'discovered')),
    sort_weight integer NOT NULL DEFAULT 0,
    -- Last run that reached this provider, and the last one that confirmed its catalogue.
    checked_at timestamptz,
    verified_at timestamptz,
    error text,
    -- Since when the pages have left out most listed models; a hold that lasts a week is accepted.
    held_since timestamptz,
    state_changed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE llm_sources (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_id text NOT NULL REFERENCES llm_vendors(id) ON DELETE CASCADE,
    kind text NOT NULL CONSTRAINT llm_sources_kind_valid CHECK (kind IN ('pricing', 'models', 'changelog')),
    url text NOT NULL CONSTRAINT llm_sources_url_valid CHECK (url ~ '^https://' AND char_length(url) <= 500),
    -- Prices are read only from pricing pages, in the currency that page states.
    currency text CONSTRAINT llm_sources_currency_valid CHECK (currency IN ('USD', 'CNY')),
    sort_weight integer NOT NULL DEFAULT 0,
    -- Text and digest of the last complete read. An unchanged page is not read again, and
    -- a model the previous text already named is not reported as new.
    content text,
    content_hash bytea,
    checked_at timestamptz,
    changed_at timestamptz,
    failures integer NOT NULL DEFAULT 0,
    error text,
    CONSTRAINT llm_sources_unique UNIQUE (vendor_id, url),
    CONSTRAINT llm_sources_currency_kind CHECK ((kind = 'pricing') = (currency IS NOT NULL))
);

CREATE TABLE llm_models (
    vendor_id text NOT NULL REFERENCES llm_vendors(id) ON DELETE CASCADE,
    model_id text NOT NULL CONSTRAINT llm_models_id_valid CHECK (char_length(model_id) BETWEEN 1 AND 100),
    name text NOT NULL,
    summary text NOT NULL DEFAULT '',
    summary_en text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT 'active'
        CONSTRAINT llm_models_status_valid CHECK (status IN ('preview', 'active', 'legacy', 'deprecated')),
    knowledge_cutoff text NOT NULL DEFAULT '',
    context_tokens integer CONSTRAINT llm_models_context_valid CHECK (context_tokens > 0),
    max_output_tokens integer CONSTRAINT llm_models_output_valid CHECK (max_output_tokens > 0),
    input_modalities text[] NOT NULL DEFAULT '{}',
    output_modalities text[] NOT NULL DEFAULT '{}',
    features text[] NOT NULL DEFAULT '{}',
    -- Verified price rows per 1M tokens; see src/llm.rs `Price`.
    prices jsonb NOT NULL DEFAULT '[]',
    -- Official documentation and announcement pages found on the provider's own pages.
    links jsonb NOT NULL DEFAULT '{}',
    -- Page URLs and verbatim excerpts behind the published values.
    evidence jsonb NOT NULL DEFAULT '{}',
    -- Order within the provider as its own pages list the models, flagship first.
    position integer NOT NULL DEFAULT 0,
    hidden boolean NOT NULL DEFAULT false,
    first_seen_at timestamptz NOT NULL DEFAULT now(),
    verified_at timestamptz NOT NULL DEFAULT now(),
    changed_at timestamptz NOT NULL DEFAULT now(),
    -- Set once the provider's pages no longer mention the model; cleared if it returns.
    removed_at timestamptz,
    PRIMARY KEY (vendor_id, model_id)
);

-- Append-only history: the recent-changes list, the Atom feed and each model's price history.
-- Providers joining and leaving are recorded without a model.
CREATE TABLE llm_changes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_id text NOT NULL REFERENCES llm_vendors(id) ON DELETE CASCADE,
    model_id text,
    kind text NOT NULL CONSTRAINT llm_changes_kind_valid
        CHECK (kind IN ('added', 'price', 'spec', 'status', 'removed', 'vendor_added', 'vendor_removed')),
    before jsonb,
    after jsonb,
    source_url text NOT NULL DEFAULT '',
    detected_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT llm_changes_subject_valid
        CHECK ((kind IN ('vendor_added', 'vendor_removed')) = (model_id IS NULL)),
    FOREIGN KEY (vendor_id, model_id) REFERENCES llm_models(vendor_id, model_id) ON DELETE CASCADE
);
CREATE INDEX llm_changes_recent_idx ON llm_changes (detected_at DESC, id DESC);
CREATE INDEX llm_changes_model_idx ON llm_changes (vendor_id, model_id, detected_at DESC);

-- Destinations are Wikidata items with an English Wikivoyage guide; `voyage`, `wiki_zh` and
-- `wiki_en` name the pages the guide is written from.
CREATE TABLE travel_places (
    id text PRIMARY KEY CHECK (id ~ '^Q[1-9][0-9]{0,11}$'),
    slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND char_length(slug) <= 80),
    name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 120),
    name_en text NOT NULL CHECK (char_length(name_en) BETWEEN 1 AND 120),
    country_id text NOT NULL CHECK (country_id ~ '^Q[1-9][0-9]{0,11}$'),
    country text NOT NULL,
    country_en text NOT NULL,
    latitude double precision NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude double precision NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    voyage text NOT NULL,
    wiki_zh text,
    wiki_en text,
    guide jsonb,
    guide_at timestamptz,
    guide_attempts smallint NOT NULL DEFAULT 0,
    CONSTRAINT travel_places_guide_written CHECK ((guide IS NULL) = (guide_at IS NULL))
);
CREATE INDEX travel_places_pending_idx ON travel_places (guide_attempts) WHERE guide IS NULL;

-- `spot_id` is the place the traveler named, which may lie inside the destination. The cover is
-- the item's image, which the media refresh renews; `extra_photos` keeps the post's other
-- photographs, in order.
CREATE TABLE travel_moments (
    item_id uuid PRIMARY KEY REFERENCES items(id) ON DELETE CASCADE,
    place_id text NOT NULL REFERENCES travel_places(id),
    spot_id text NOT NULL CHECK (spot_id ~ '^Q[1-9][0-9]{0,11}$'),
    spot text NOT NULL,
    spot_en text NOT NULL,
    extra_photos jsonb NOT NULL
        CHECK (jsonb_typeof(extra_photos) = 'array' AND jsonb_array_length(extra_photos) <= 3),
    text text NOT NULL,
    lang text NOT NULL,
    -- The likes the post had when X confirmed it, which pick the map's favorites.
    likes bigint CHECK (likes >= 0)
);
CREATE INDEX travel_moments_place_idx ON travel_moments (place_id);
CREATE INDEX travel_moments_spot_idx ON travel_moments (spot_id);
-- Culture and 𝑮𝒂𝒅𝒈𝒆𝒕𝒔 share one catalogue. An entry is a work or a product, known by its stable
-- key: Culture's kind and English title, 𝑮𝒂𝒅𝒈𝒆𝒕𝒔' brand and model. Its guide is written only from
