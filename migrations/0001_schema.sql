CREATE TABLE plans (
    code text PRIMARY KEY CHECK (code ~ '^[a-z][a-z0-9_-]{0,31}$'),
    name text NOT NULL,
    price_fen bigint NOT NULL CHECK (price_fen >= 0),
    duration_days integer NOT NULL CHECK (duration_days BETWEEN 0 AND 3650),
